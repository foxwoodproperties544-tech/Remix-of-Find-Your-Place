## Common Mistakes to Avoid

>> Most Airbnbs that fail in Kenya do not fail because of the market — they fail because of avoidable owner mistakes.

Watch out for:

- **Cheap mattresses and thin towels.** Guests always mention these in reviews.
- **No backup water or power.** One bad day can generate a permanent 1-star review.
- **Ignoring the house rules.** Vague rules invite parties and damage.
- **Slow replies.** Airbnb penalises hosts who reply in over an hour.
- **DIY photos.** Phone photos in poor light lose you thousands per month.
- **Renting from a landlord who bans subletting.** You can be evicted with no notice.
- **Skipping insurance.** Airbnb''s AirCover is not a full replacement for local cover.

