## Legal Requirements and Licences in Kenya

Running an Airbnb is a business, and the government treats it as one. Skipping paperwork can lead to fines or closure.

Here is what you need:

| Requirement | Where to get it | Approx. cost |
|---|---|---|
| KRA PIN | [KRA iTax](https://itax.kra.go.ke/) | Free |
| Single Business Permit | County government | KES 10,000 – 30,000 / year |
| Tourism Regulatory Authority (TRA) licence | [eCitizen / TRA](https://www.ecitizen.go.ke/) | KES 5,000 – 25,000 / year |
| Fire safety certificate | County / Fire dept. | KES 3,000 – 10,000 |
| Health inspection certificate | County health office | KES 2,000 – 5,000 |
| NEMA compliance (large units) | NEMA | Varies |

You will also pay:

- **Income tax** on your earnings (individual rates or turnover tax if you earn under KES 25M/year).
- **Catering Levy (2%)** to the Tourism Fund on gross sales.
- **VAT (16%)** if annual turnover exceeds KES 5 million.

:::note
Airbnb has begun collecting **7.5% Digital Service Tax** and Tourism Levy from Kenyan hosts on your behalf in some cases. Confirm on your Airbnb payout statement so you do not double-pay.
:::

## Business Registration (if applicable)

If you plan to run more than one unit or open a bank account for the business, register a limited company or a business name on [eCitizen](https://www.ecitizen.go.ke/). Costs are around KES 950 for a business name and KES 10,650 for a private limited company.

Benefits of registering:

- Separates personal and business finances.
- Makes it easier to bring on investors or a co-host.
- Improves your credibility with landlords and guests.

## Pricing Your Airbnb

Pricing is part art, part data. Set prices too high and you sit empty; too low and you leave money on the table.

**A simple starting formula:**

1. Look up 5–10 similar listings in your neighbourhood on Airbnb.
2. Take the average nightly rate.
3. Start 10–15% below that for your first 30 days to attract early bookings and reviews.
4. Raise prices gradually as your reviews grow.

**Use dynamic pricing:**

- Charge more on Fridays, Saturdays and public holidays.
- Charge more during high season (December, Easter, August).
- Offer 10–20% weekly and 25–40% monthly discounts to attract longer stays.

Tools like **PriceLabs**, **Beyond Pricing** or Airbnb's built-in **Smart Pricing** can automate this once you have some booking history.

## Marketing Your Airbnb

The Airbnb algorithm rewards new listings with a small boost in the first 30 days. Use that window well.

**On-platform tips:**

- Hire a professional photographer (KES 5,000 – 15,000). Photos are the #1 conversion driver.
- Write a benefit-driven title: "Bright 1BR near Sarit Mall • Fast Wi-Fi • Netflix".
- Fill in every amenity — the algorithm uses this for filters.
- Respond to messages within one hour. Response rate directly affects ranking.
- Aim for 5-star reviews on the first 10 stays. Ask happy guests politely.

**Off-platform marketing:**

- Create an Instagram page for your unit and post reels.
- Join Kenyan Airbnb host Facebook and WhatsApp groups.
- List your unit on Booking.com and Vrbo to diversify income.
- Ask corporate clients (embassies, NGOs, film crews) directly for long stays.
