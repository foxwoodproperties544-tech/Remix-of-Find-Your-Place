## Tips for Success

- **Automate check-in** with a smart lock or lockbox — no midnight arrivals waking you up.
- **Use a professional cleaner** and pay for a same-day turnover. Never clean between guests yourself once you have more than one unit.
- **Create a simple digital welcome book** on Canva with Wi-Fi password, house rules, and local restaurant tips.
- **Photograph every corner before each guest arrives.** This protects you if damage is claimed.
- **Reinvest your first 6 months of profit** into upgrades — better bedding, a coffee machine, blackout curtains. Small upgrades lift your review score.
- **Track everything in a simple spreadsheet**: nights booked, revenue, cleaning costs, supplies. You cannot improve what you do not measure.

## Frequently Asked Questions (FAQ)

### How much can I earn from an Airbnb in Kenya?
A well-run one-bedroom in Nairobi can gross **KES 90,000 – 180,000 per month** at 60–70% occupancy. Coastal cottages and Nanyuki cabins can earn more during high season.

### Do I need to own the property to start?
No. Many successful hosts rent long-term and sublet — but you must have written permission from the landlord.

### Is an Airbnb business legal in Kenya?
Yes. You need a KRA PIN, a Single Business Permit from your county, and a TRA licence. Some counties also require a fire and health inspection.

### How long does it take to become profitable?
Most new Airbnbs need 3–6 months to build reviews and reach steady occupancy. Full payback of setup costs usually takes 6–12 months.

### Can I run an Airbnb while working a full-time job?
Yes, but only if you outsource cleaning and use tools for automated messaging and pricing. Otherwise it will consume every evening.

### What insurance do I need?
Take out a landlord/short-let insurance policy from a Kenyan insurer. Airbnb''s built-in AirCover helps but has strict limits and slow claim times.

