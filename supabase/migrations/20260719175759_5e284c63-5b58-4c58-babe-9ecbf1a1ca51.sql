## Choosing the Right Location

Location is the single biggest factor in Airbnb success. A beautiful apartment in the wrong area will sit empty; an average unit in a hot area will book out every weekend.

**High-demand areas in Kenya include:**

- **Nairobi**: Kilimani, Westlands, Lavington, Kileleshwa, Upper Hill, Riverside, Parklands and areas near JKIA such as Syokimau.
- **Coast**: Nyali, Bamburi, Diani, Watamu and Malindi.
- **Getaway towns**: Naivasha, Nanyuki, Nakuru, Kisumu and Eldoret.

Ask yourself:

- Is it close to conference venues, hospitals, malls or beaches?
- Is the neighbourhood safe, especially at night?
- Are there restaurants, supermarkets and taxis nearby?
