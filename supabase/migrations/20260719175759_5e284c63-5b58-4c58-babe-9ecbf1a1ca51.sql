## Furnishing Your Airbnb

Guests compare your listing to hotels. The photos and the first five minutes after check-in decide your reviews — and reviews decide your bookings.

**Bedroom essentials:**

- Quality mattress (not the cheapest — guests always mention this).
- Two sets of white cotton bedding per bed.
- Blackout curtains.
- Bedside lamps with USB charging.

**Living area essentials:**

- Comfortable 3- or 5-seater sofa.
- Smart TV with Netflix or DStv Now.
- Coffee table and dining set.
- Decor that looks great in photos — art, plants, throw pillows.

**Kitchen essentials:**

- Fridge, microwave, cooker and kettle.
- Full cutlery, plates, glasses, mugs and cookware for the maximum guest count.
- Basic starter pack: salt, sugar, tea bags, cooking oil, coffee.

**Bathroom essentials:**

- Instant hot shower.
- Fluffy white towels (two per guest).
- Toiletries: hand soap, body wash, shampoo, toilet paper.

:::tip
Buy in white where possible — sheets, towels and crockery. White is easy to bleach clean and photographs beautifully.
