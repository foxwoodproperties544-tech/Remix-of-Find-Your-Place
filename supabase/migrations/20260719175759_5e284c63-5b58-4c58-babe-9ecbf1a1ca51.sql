## Finding the Right Property

Once you have chosen a location, you have three main options:

1. **Use a property you already own.** The cheapest way to start — no rent, higher margins.
2. **Rent-to-rent (sublet).** You lease a unit long-term, get written permission to sublet, then list it on Airbnb.
3. **Buy a new property specifically for Airbnb.** Best long-term play, but needs the most capital.

:::warning
Never sublet a property without written permission from the landlord and the management company. Many gated estates and apartment blocks now ban short-stays entirely. Confirm in writing before signing anything.
:::

Look for units with:

- A separate lockable entrance (so long-term neighbours are not disturbed).
- Reliable water — a borehole or good tank storage is essential.
- Backup power or an inverter.
- Ample secure parking.
- Fibre internet coverage (Safaricom Home Fibre, Zuku or Faiba).

